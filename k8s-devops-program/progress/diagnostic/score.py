#!/usr/bin/env python3
"""Week 1 diagnostic scorer.

Reads   auto-scores.csv    (written by labs/week-01/grade.sh)
        manual-scores.csv  (Part A, Part D, speed drill, career audit - you/coach fill 'earned')
        self-ratings.csv   (your 0-4 self-ratings, filled BEFORE the diagnostic)
Writes  report.md          (domain levels, week tiers, hour reallocation, triggers)

The rules implemented here are documented in curriculum/adaptation-rules.md.
If you change one, change the other. Stdlib only.
"""
import csv
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

DOMAINS = {
    "D1": "Linux & networking fundamentals",
    "D2": "Containers & images",
    "D3": "Workloads & configuration",
    "D4": "Services & cluster networking",
    "D5": "Storage & scheduling",
    "D6": "Troubleshooting",
    "D7": "RBAC & security",
    "D8": "Packaging (Helm/Kustomize)",
    "D9": "IaC & AWS (Terraform/EKS)",
    "D10": "CI/CD & GitOps",
    "D11": "Observability",
    "D12": "Cluster administration",
    "D13": "kubectl speed",
    "D14": "Career readiness",
}

# Week -> primary domains (curriculum/adaptation-rules.md, table 2)
WEEKS = {
    2: ("Core K8s I: workloads & config", ["D2", "D3"]),
    3: ("Core K8s II: networking, storage, scheduling", ["D4", "D5"]),
    4: ("Troubleshooting & RBAC", ["D6", "D7"]),
    5: ("Helm & Kustomize", ["D8"]),
    6: ("Terraform & EKS", ["D9"]),
    7: ("CI/CD & GitOps", ["D10"]),
    8: ("Observability", ["D11"]),
    9: ("Security", ["D7", "D2"]),
}

# CKA curriculum weights mapped onto diagnostic domains
CKA_WEIGHTS = {"D6": 0.30, "D4": 0.20, "D12": 0.15, "D7": 0.10, "D3": 0.15, "D5": 0.10}

BASE_HOURS = 9.0
FOUNDATION_EXTRA = 1.0   # foundation week runs at 10 h
FASTTRACK_FREED = 2.0    # fast-track week runs at 7 h, 2 h banked


def level(pct):
    if pct is None:
        return None
    if pct >= 85: return 4
    if pct >= 60: return 3
    if pct >= 40: return 2
    if pct >= 20: return 1
    return 0


def read_rows(name):
    path = os.path.join(HERE, name)
    if not os.path.exists(path):
        return []
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def main():
    rows = read_rows("auto-scores.csv") + read_rows("manual-scores.csv")
    earned = {d: 0.0 for d in DOMAINS}
    maxed = {d: 0.0 for d in DOMAINS}
    ungraded = []
    for r in rows:
        d = r["domain"].strip()
        if d not in DOMAINS:
            continue
        e = (r.get("earned") or "").strip()
        if e == "":
            ungraded.append(r["item"])
            continue
        earned[d] += float(e)
        maxed[d] += float(r["max"])

    self_r = {r["domain"].strip(): r.get("rating", "").strip() for r in read_rows("self-ratings.csv")}

    pct = {d: (100.0 * earned[d] / maxed[d]) if maxed[d] else None for d in DOMAINS}
    lvl = {d: level(pct[d]) for d in DOMAINS}

    out = []
    w = out.append
    w("# Week 1 Diagnostic Report\n")
    w("_Generated by `progress/diagnostic/score.py`. Do not hand-edit; re-run instead._\n")
    if ungraded:
        w(f"> **Incomplete:** {len(ungraded)} item(s) have no score yet: {', '.join(ungraded[:20])}"
          f"{' ...' if len(ungraded) > 20 else ''}. Levels below ignore them.\n")

    w("## 1. Domain levels\n")
    w("| Domain | Area | Points | % | Level (0-4) | Self-rating | Gap |")
    w("|---|---|---|---|---|---|---|")
    gaps = []
    for d, name in DOMAINS.items():
        p = "-" if pct[d] is None else f"{pct[d]:.0f}%"
        l = "-" if lvl[d] is None else str(lvl[d])
        s = self_r.get(d, "")
        gap = ""
        if s and lvl[d] is not None:
            g = int(s) - lvl[d]
            gap = f"{g:+d}"
            if g >= 2:
                gaps.append(d)
        w(f"| {d} | {name} | {earned[d]:g}/{maxed[d]:g} | {p} | {l} | {s or '-'} | {gap} |")
    w("")
    w("Levels: 0 none - 1 recognize - 2 assisted - 3 independent - 4 fluent. "
      "Gap = self-rating minus measured; **+2 or more = overconfidence flag**.\n")

    # Week tiers
    w("## 2. Week tiers (weeks 2-9)\n")
    w("| Week | Topic | Domains | Avg level | Tier | Planned hours |")
    w("|---|---|---|---|---|---|")
    bank = 0.0
    tiers = {}
    for wk, (topic, ds) in WEEKS.items():
        vals = [lvl[d] for d in ds if lvl[d] is not None]
        if not vals:
            tiers[wk] = ("Standard", BASE_HOURS, None)
        else:
            avg = sum(vals) / len(vals)
            if avg < 1.5:
                tiers[wk] = ("Foundation", BASE_HOURS + FOUNDATION_EXTRA, avg)
            elif avg >= 3:
                tiers[wk] = ("Fast-track", BASE_HOURS - FASTTRACK_FREED, avg)
                bank += FASTTRACK_FREED
            else:
                tiers[wk] = ("Standard", BASE_HOURS, avg)
        t, h, a = tiers[wk]
        w(f"| {wk} | {topic} | {', '.join(ds)} | {'-' if a is None else f'{a:.1f}'} | **{t}** | {h:g} h |")
    w("")

    # Bank allocation
    w("## 3. Hour bank\n")
    w(f"Hours freed by fast-track weeks: **{bank:g} h**.\n")
    cka_weak = [d for d in ("D12", "D13", "D6") if lvl[d] is not None and lvl[d] <= 1]
    if bank:
        if cka_weak:
            w(f"- Spend banked hours first on CKA weak spots ({', '.join(cka_weak)}): "
              "extra drill/mock sessions in weeks 10-11 (cap 10 h/week; overflow goes to the capstone).")
        else:
            w("- No CKA domain is weak: spend banked hours on the capstone and the job-search track.")
    else:
        w("- Nothing banked. Foundation weeks must stay within 10 h by cutting optional reading, not labs.")
    w("")

    # Triggers
    w("## 4. Triggered adjustments\n")
    trig = []
    if lvl["D13"] is not None and lvl["D13"] <= 2:
        trig.append("**Speed (D13 <= 2):** daily 15-min kubectl drill, 5x/week from Week 2 "
                    "(counts as 1.25 h of each week's budget).")
    if lvl["D1"] is not None and lvl["D1"] <= 1:
        trig.append("**Linux/networking (D1 <= 1):** add a 1 h fundamentals block to weeks 2, 3 and 4 "
                    "(systemd/journalctl, ss/ip/dig/curl, CIDR math).")
    if lvl["D14"] is not None and lvl["D14"] <= 1:
        trig.append("**Career (D14 <= 1):** job-search track starts in Week 2 at 1 h/week instead of Week 6.")
    elif lvl["D14"] is not None:
        trig.append("Career track starts Week 6 at 1 h/week (default).")
    if lvl["D9"] is not None and lvl["D9"] >= 3:
        trig.append("**AWS strength (D9 >= 3):** Week 6 skips Terraform basics; goes straight to "
                    "modules, remote state, EKS + Pod Identity.")
    for d in gaps:
        trig.append(f"**Overconfidence ({d}):** re-test {d} with a fresh timed task at the end of the week that covers it.")
    if not trig:
        trig.append("None.")
    for t in trig:
        w(f"- {t}")
    w("")

    # CKA projection
    w("## 5. CKA readiness projection\n")
    num = sum(CKA_WEIGHTS[d] * pct[d] for d in CKA_WEIGHTS if pct[d] is not None)
    den = sum(CKA_WEIGHTS[d] for d in CKA_WEIGHTS if pct[d] is not None)
    if den:
        cka = num / den
        w(f"Weighted baseline on CKA domains: **{cka:.0f}%** (exam pass mark is 66%).\n")
        if cka >= 60:
            w("- **On track.** Buy the exam voucher after the Week 4 checkpoint; book a Week 12 slot.")
        elif cka >= 35:
            w("- **Plausible.** Plan for Week 12. Decide at the Week 8 checkpoint "
              "(need >= 60% on that mini-mock to book).")
        else:
            w("- **Stretch.** Plan the exam for Week 13-14 and use Week 12 for a full mock + portfolio. "
              "Do not buy the voucher before the Week 8 checkpoint.")
    else:
        w("Not enough data.")
    w("")

    # Capstone scope
    w("## 6. Capstone scope\n")
    tot_e = sum(earned[d] for d in DOMAINS if d != "D14")
    tot_m = sum(maxed[d] for d in DOMAINS if d != "D14")
    overall = 100 * tot_e / tot_m if tot_m else 0
    if overall >= 70:
        scope = "Tier 3 - Platform (see capstone/README.md)"
    elif overall >= 40:
        scope = "Tier 2 - Production app (see capstone/README.md)"
    else:
        scope = "Tier 1 - Solid foundation (see capstone/README.md)"
    w(f"Overall technical score: **{overall:.0f}%** -> **{scope}**.\n")

    # Top 3 weakest
    ranked = sorted([d for d in DOMAINS if lvl[d] is not None and d != "D14"], key=lambda d: (pct[d], d))
    w("## 7. Three weakest technical domains\n")
    for d in ranked[:3]:
        w(f"- {d} {DOMAINS[d]} ({pct[d]:.0f}%)")
    w("")

    report = "\n".join(out)
    with open(os.path.join(HERE, "report.md"), "w") as f:
        f.write(report + "\n")
    print(report)


if __name__ == "__main__":
    sys.exit(main())
